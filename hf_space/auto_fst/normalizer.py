class RussianLayoutNormalizer:
    def __init__(self, custom_map: Optional[Dict[str, str]] = None):
        self.word_map = dict(HIGH_FREQ_RUSSIAN_LAYOUT_MAP)
        if custom_map:
            self.word_map.update(custom_map)

    def normalize_word(self, word: str) -> str:
        w_lower = word.lower()
        if w_lower in self.word_map:
            mapped = self.word_map[w_lower]
            if word.isupper():
                return mapped.upper()
            elif word.istitle():
                return mapped.capitalize()
            return mapped

        # Apply harmonic suffix regex restoration if not directly in map
        for pat, repl in HARMONIC_SUFFIX_PATTERNS:
            if pat.match(word):
                return pat.sub(repl, word)

        return word

    def normalize_text(self, text: str) -> str:
        if not text:
            return ""
        tokens = re.split(r'(\s+|[^\w\s])', text)
        result = []
        for token in tokens:
            if re.match(r'^[а-яёәіңғүұқөһА-ЯЁӘІҢҒҮҰҚӨҺ]+$', token):
                result.append(self.normalize_word(token))
            else:
                result.append(token)
        return "".join(result)

    def has_russian_layout_artifacts(self, word: str) -> bool:
        w_lower = word.lower()
        if w_lower in self.word_map:
            return True
        for pat, _ in HARMONIC_SUFFIX_PATTERNS:
            if pat.match(word):
                return True
        return False
