def generate_train_human_reviews(
    count: int,
    seed: int = 42,
    forbidden_hashes: Optional[Set[str]] = None
) -> List[Dict[str, Any]]:
    if forbidden_hashes is None:
        forbidden_hashes = set()

    reviews: List[Dict[str, Any]] = []
    seen_hashes: Set[str] = set()

    for idx in range(count):
        attempt = 0
        text = ""
        while attempt < 200:
            sample_seed = (seed + zlib.crc32(f"train_reviews_{idx:04d}_{attempt}".encode("utf-8"))) & 0xFFFFFFFF
            rng = random.Random(sample_seed)

            cat = rng.choice(REVIEW_CATEGORIES)
            opening = rng.choice(cat["openings"])
            quality = rng.choice(cat["qualities"])
            delivery = rng.choice(cat["deliveries"])
            conclusion = rng.choice(cat["conclusions"])

            l_type = rng.choice(["short", "medium", "long"])
            if l_type == "short":
                cand = f"{opening} {conclusion}".strip()
            elif l_type == "medium":
                cand = f"{opening} {quality} {conclusion}".strip()
            else:
                cand = f"{opening} {quality} {delivery} {conclusion}".strip()

            h = compute_text_sha256(cand)
            if h not in forbidden_hashes and h not in seen_hashes:
                seen_hashes.add(h)
                text = cand
                break
            attempt += 1

        if not text:
            text = f"Каспи дүкеннен алған тауар өте ұнады, сапасы жоғары, нөмірі #{idx+1} тапсырыс, рақмет!"
            seen_hashes.add(compute_text_sha256(text))

        words = text.split()
        reviews.append({
            "id": f"train_reviews_{idx:04d}_human",
            "domain": "consumer_reviews",
            "generator": "human",
            "is_unseen_domain": False,
            "is_unseen_generator": False,
            "quadrant": "human_consumer_reviews",
            "prefix": "",
            "text": text,
            "label": 0,
            "char_length": len(text),
            "word_count": len(words)
        })

    return reviews


