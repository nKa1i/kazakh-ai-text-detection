def normalize_text_for_hash(text: str) -> str:
    return " ".join(str(text).strip().lower().split())


def compute_text_sha256(text: str) -> str:
    normalized = normalize_text_for_hash(text)
    return hashlib.sha256(normalized.encode("utf-8")).hexdigest()


def audit_dataset_isolation(train_path: str, eval_path: str) -> Dict[str, Any]:
    if not os.path.exists(train_path):
        raise FileNotFoundError(f"Training dataset not found at {train_path}")
    if not os.path.exists(eval_path):
        raise FileNotFoundError(f"Evaluation benchmark not found at {eval_path}")

    with open(train_path, "r", encoding="utf-8") as f:
        train_data = json.load(f)
    with open(eval_path, "r", encoding="utf-8") as f:
        eval_data = json.load(f)

    train_hashes: Set[str] = set()
    for item in train_data:
        norm_t = normalize_text_for_hash(item.get("text", ""))
        if norm_t:
            train_hashes.add(hashlib.sha256(norm_t.encode("utf-8")).hexdigest())

    eval_hashes: Set[str] = set()
    for item in eval_data:
        norm_t = normalize_text_for_hash(item.get("text", ""))
        if norm_t:
            eval_hashes.add(hashlib.sha256(norm_t.encode("utf-8")).hexdigest())

    overlap = train_hashes.intersection(eval_hashes)

    return {
        "train_count": len(train_hashes),
        "eval_count": len(eval_hashes),
        "overlap_count": len(overlap),
        "is_clean": len(overlap) == 0,
        "overlapping_hashes": list(overlap)
    }


def extract_prefix(text: str, num_words: int = 20) -> str:
    tokens = text.strip().split()
    if len(tokens) <= num_words:
        return text.strip()
    return " ".join(tokens[:num_words])


