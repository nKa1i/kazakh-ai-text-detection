def segment_sentences_kazakh(text: str) -> List[str]:
    """
    Split Kazakh text into sentences respecting abbreviations.
    Handles abbreviations such as ж., ғ., т.б., б.з.д., мыс., проф., акад.
    """
    clean = text.strip()
    placeholder_map = {}
    sorted_abbrs = sorted(KAZAKH_ABBREVIATIONS, key=len, reverse=True)
    for idx, abb in enumerate(sorted_abbrs):
        token = f"<ABB_{idx}>"
        placeholder_map[token] = abb
        # Use negative lookbehind for word chars to prevent matching word endings like 'халық.'
        clean = re.sub(r"(?<![A-Za-zА-Яа-яӘәІіҢңҒғҮүҰұҚқӨөҺһ])" + re.escape(abb), token, clean)

    parts = re.split(r"(?<=[.!?])\s+", clean)
    sentences = []
    for p in parts:
        p_clean = p.strip()
        for token, abb in placeholder_map.items():
            p_clean = p_clean.replace(token, abb)
        if p_clean and any(c.isalnum() for c in p_clean):
            sentences.append(p_clean)
    return sentences


def validate_knowledge_passage(passage: Any) -> bool:
    """
    Validate knowledge passage schema, non-empty fields, domain, character length and word count.
    """
    if not isinstance(passage, dict):
        return False

    required_keys = {"passage_id", "title", "text", "domain"}
    if not required_keys.issubset(passage.keys()):
        return False

    for k in required_keys:
        val = passage[k]
        if not isinstance(val, str) or not val.strip():
            return False

    domain = passage["domain"].strip().lower()
    if domain not in VALID_DOMAINS:
        return False

    text = passage["text"].strip()
    if len(text) < 50 or len(text.split()) < 10:
        return False

    return True


def build_curated_knowledge_corpus(
    output_path: str = "kaggle_runner/kazakh_knowledge_corpus.jsonl",
) -> List[Dict[str, Any]]:
    """
    Build and save curated multi-domain Kazakh knowledge passages.
    Generates 60+ passages across 8 thematic domains.
    """
    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    passages = []
    for item in CURATED_ARTICLES:
        rec = {
            "passage_id": item["passage_id"],
            "title": item["title"],
            "text": item["text"],
            "domain": item["domain"],
        }
        if validate_knowledge_passage(rec):
            passages.append(rec)

    with open(output_path, "w", encoding="utf-8") as f:
        for p in passages:
            f.write(json.dumps(p, ensure_ascii=False) + "\n")

    return passages


