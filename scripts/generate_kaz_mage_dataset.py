# ---------------------------------------------------------------------------
# Helper: Prefix Extraction
# ---------------------------------------------------------------------------

def extract_prefix(text: str, num_words: int = 20) -> str:
    """
    Extract the first num_words words from the text as a prefix.
    If text has fewer words, return the stripped text.
    """
    tokens = text.strip().split()
    if len(tokens) <= num_words:
        return text.strip()
    return " ".join(tokens[:num_words])


