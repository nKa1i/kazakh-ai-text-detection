def assemble_kaz_mage_dataset(
    output_path: str = "data/kaz_mage_eval_6k.json",
    num_samples_per_domain: int = 500,
    seed: int = 42,
    seed_reviews_path: str = "data/seed_human_reviews_1k.json",
    review_samples: Optional[int] = None
) -> List[Dict[str, Any]]:
    """
    Assemble the complete Kaz-MAGE benchmark dataset matching the ACL 2024 MAGE protocol.

    Args:
        output_path: Path to output JSON file.
        num_samples_per_domain: Number of human samples for news and wikipedia (default: 500).
        seed: Random seed for process-invariant reproducibility.
        seed_reviews_path: Path to human reviews seed file.
        review_samples: Number of human reviews to include. Defaults to 1000 for full (500/domain)
                        eval or num_samples_per_domain for mini tests.

    Returns:
        List of all assembled benchmark records.
    """
    if review_samples is None:
        review_samples = 1000 if num_samples_per_domain >= 500 else num_samples_per_domain

    print(f"Loading/generating human texts (Reviews: {review_samples}, News: {num_samples_per_domain}, Wiki: {num_samples_per_domain})...")

    human_reviews = load_or_generate_human_reviews(
        count=review_samples,
        seed=seed,
        seed_path=seed_reviews_path
    )
    human_news = generate_human_news_articles(
        count=num_samples_per_domain,
        seed=seed + 10
    )
    human_wiki = generate_human_wikipedia_articles(
        count=num_samples_per_domain,
        seed=seed + 20
    )

    dataset: List[Dict[str, Any]] = []

    # 1. Consumer Reviews (Seen Domain):
    #    Human (label 0)
    #    Sherkala-7B (Q1)
    #    Qwen-2.5-7B-Instruct (Q2)
    for h in human_reviews:
        dataset.append(h)
        dataset.append(build_synthetic_pair(h, generator="Sherkala-7B", seed=seed))
        dataset.append(build_synthetic_pair(h, generator="Qwen-2.5-7B-Instruct", seed=seed))

    # 2. Formal News (Unseen Domain):
    #    Human (label 0)
    #    Sherkala-7B (Q3)
    #    Qwen-2.5-7B-Instruct (Q4)
    for h in human_news:
        dataset.append(h)
        dataset.append(build_synthetic_pair(h, generator="Sherkala-7B", seed=seed))
        dataset.append(build_synthetic_pair(h, generator="Qwen-2.5-7B-Instruct", seed=seed))

    # 3. Kazakh Wikipedia (Unseen Domain):
    #    Human (label 0)
    #    Sherkala-7B (Q3)
    #    Qwen-2.5-7B-Instruct (Q4)
    for h in human_wiki:
        dataset.append(h)
        dataset.append(build_synthetic_pair(h, generator="Sherkala-7B", seed=seed))
        dataset.append(build_synthetic_pair(h, generator="Qwen-2.5-7B-Instruct", seed=seed))

    # Ensure output directory exists
    out_dir = os.path.dirname(output_path)
    if out_dir:
        os.makedirs(out_dir, exist_ok=True)

    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(dataset, f, ensure_ascii=False, indent=2)

    quad_counts: Dict[str, int] = {}
    for d in dataset:
        q = d["quadrant"]
        quad_counts[q] = quad_counts.get(q, 0) + 1

    print(f"[Done] Assembled Kaz-MAGE dataset with {len(dataset)} total samples.")
    print(f"       Quadrant distribution: {quad_counts}")
    print(f"       Saved to: {output_path}")

    return dataset


