def generate_continuation(
    prefix: str,
    domain: str,
    generator: str,
    human_text: str,
    rng: random.Random
) -> str:
    """
    Generate synthetic continuation starting with `prefix`, conditioned on generator style,
    domain, and length matching human text (+/- 15%).
    """
    human_words = len(human_text.split())

    if domain == "consumer_reviews":
        # Short review continuation
        if "sherkala" in generator.lower():
            pattern = rng.choice(SHERKALA_REVIEW_PATTERNS)
        else:
            pattern = rng.choice(QWEN_REVIEW_PATTERNS)
        # Combine prefix and pattern cleanly
        continuation_text = f"{prefix} {pattern}".strip()
        return continuation_text

    # Formal News or Wikipedia continuation
    if "sherkala" in generator.lower():
        pool = SHERKALA_NEWS_PATTERNS if domain == "news" else SHERKALA_WIKI_PATTERNS
    else:
        pool = QWEN_NEWS_PATTERNS if domain == "news" else QWEN_WIKI_PATTERNS

    # Pick chunks to match target length
    continuation_chunks = [rng.choice(pool)]
    if human_words > 120:
        continuation_chunks.append(rng.choice(pool))

    body = " ".join(continuation_chunks)
    full_text = f"{prefix} {body}".strip()

    # If target length requires trimming or keeping within bounds
    target_words = max(human_words, 150)
    current_words = full_text.split()
    if len(current_words) > target_words + 20:
        # Trim at sentence boundary if possible
        trimmed = " ".join(current_words[:target_words])
        last_dot = max(trimmed.rfind("."), trimmed.rfind("!"), trimmed.rfind("?"))
        if last_dot > len(prefix):
            full_text = trimmed[:last_dot + 1]
        else:
            full_text = trimmed + "."

    return full_text


def build_synthetic_pair(
    human_sample: Dict[str, Any],
    generator: str = "Sherkala-7B",
    seed: int = 42,
    num_prefix_words: Optional[int] = None
) -> Dict[str, Any]:
    """
    Construct a synthetic AI record paired with a human sample using the prefix continuation paradigm.

    Quadrant mapping:
    - consumer_reviews + Sherkala-7B          -> Q1 (seen domain, seen LLM)
    - consumer_reviews + Qwen-2.5-7B-Instruct  -> Q2 (seen domain, unseen LLM)
    - news/wikipedia   + Sherkala-7B          -> Q3 (unseen domain, seen LLM)
    - news/wikipedia   + Qwen-2.5-7B-Instruct  -> Q4 (unseen domain, unseen LLM)
    """
    human_text = human_sample.get("text", "").strip()
    domain = human_sample.get("domain", "news")

    if num_prefix_words is None:
        if domain == "consumer_reviews":
            num_prefix_words = min(5, max(2, len(human_text.split()) // 2))
        else:
            num_prefix_words = 20

    prefix = human_sample.get("prefix") or extract_prefix(human_text, num_words=num_prefix_words)

    # Process-invariant deterministic seed per sample
    sample_id = str(human_sample.get("id", "0"))
    sample_seed = (seed + zlib.crc32(f"{sample_id}_{generator}_{domain}".encode("utf-8"))) & 0xFFFFFFFF
    rng = random.Random(sample_seed)

    is_unseen_domain = (domain != "consumer_reviews")
    is_unseen_generator = ("sherkala" not in generator.lower())

    if not is_unseen_domain and not is_unseen_generator:
        quadrant = "Q1"
    elif not is_unseen_domain and is_unseen_generator:
        quadrant = "Q2"
    elif is_unseen_domain and not is_unseen_generator:
        quadrant = "Q3"
    else:
        quadrant = "Q4"

    synthetic_text = generate_continuation(prefix, domain, generator, human_text, rng)

    # Guarantee text starts with prefix
    if not synthetic_text.startswith(prefix):
        synthetic_text = f"{prefix} {synthetic_text}".strip()

    gen_slug = generator.lower().replace(".", "_").replace("-", "_")
    base_id = sample_id.replace("_human", "")
    ai_id = f"{base_id}_{gen_slug}"

    return {
        "id": ai_id,
        "domain": domain,
        "generator": generator,
        "is_unseen_domain": is_unseen_domain,
        "is_unseen_generator": is_unseen_generator,
        "quadrant": quadrant,
        "prefix": prefix,
        "text": synthetic_text,
        "label": 1,
        "char_length": len(synthetic_text),
        "word_count": len(synthetic_text.split())
    }


